const walkTop = (root) =>
  readdirSync(root)
    .filter((n) => n !== ".git")
    .sort((a, b) => a.localeCompare(b));

const skillNames = (root) =>
  existsSync(join(root, "skills"))
    ? readdirSync(join(root, "skills"))
        .filter((n) => existsSync(join(root, "skills", n, "SKILL.md")))
        .sort()
    : [];

const frontmatter = (text) => {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  if (!m) return null;
  const out = {};
  for (const l of m[1].split(/\r?\n/)) {
    const i = l.indexOf(":");
    if (i > 0) out[l.slice(0, i).trim()] = l.slice(i + 1).trim();
  }
  return out;
};

const readConst = (root, file, name) =>
  new RegExp(`${name}\\s*=\\s*"?([\\w.]+)"?`).exec(readFileSync(join(root, file), "utf8"))?.[1];

const oneLine = (s) => String(s).replace(/\s+/g, " ").trim();
const firstSentence = (s) => (/^(.+?[.!?])(\s|$)/.exec(oneLine(s))?.[1] ?? oneLine(s));
const esc = (s) => String(s).replace(/\|/g, "\\|");
const slug = (h) =>
  h
    .toLowerCase()
    .replace(/\*\(generated\)\*/g, "")
    .replace(/[^a-z0-9\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-");

export function loadReference(root) {
  return JSON.parse(readFileSync(join(root, "docs", "skills-reference.json"), "utf8"));
}

// ---------------------------------------------------------------- consistency checks
export function checkConsistency(root) {
  const problems = [];
  const names = skillNames(root);
  const ref = loadReference(root);
  const refNames = Object.keys(ref.skills);

  for (const n of names) if (!ref.skills[n]) problems.push(`skill ${n} exists but is undocumented (add it to docs/skills-reference.json)`);
  for (const n of refNames) if (!names.includes(n)) problems.push(`documentation references nonexistent skill ${n}`);

  for (const n of names) {
    const text = readFileSync(join(root, "skills", n, "SKILL.md"), "utf8");
    const fm = frontmatter(text);
    if (!fm || fm.name !== n) problems.push(`skills/${n}/SKILL.md: frontmatter name is "${fm?.name}", expected "${n}"`);
    const doc = ref.skills[n];
    if (!doc) continue;
    for (const f of ["purpose", "whenToUse", "syntax", "arguments", "examples", "inputs", "outputs", "automatic", "approval", "external", "safety", "next", "approvalRequired", "externalEffect"])
      if (doc[f] == null || (Array.isArray(doc[f]) && !doc[f].length) || doc[f] === "") problems.push(`${n}: documentation field "${f}" is missing`);
    // Syntax: every documented form must start with the skill's own command, and every --flag it uses must be a
    // flag the skill itself mentions.
    for (const s of doc.syntax ?? []) {
      if (s.split(/\s+/)[0] !== `/${n}`) problems.push(`${n}: documented syntax "${s}" does not start with /${n}`);
      for (const flag of s.match(/--[a-z-]+/g) ?? [])
        if (!text.includes(flag)) problems.push(`${n}: documented syntax "${s}" uses ${flag}, which the skill does not describe`);
    }
    // If the skill advertises an argument form ("invokes /X <something>"), the manual must document one too.
    const adv = new RegExp(`invokes /${n} <[^>]+>`).test(fm?.description ?? "");
    if (adv && !(doc.syntax ?? []).some((s) => /</.test(s))) problems.push(`${n}: the skill advertises an argument but the documented syntax has none`);
    // And the reverse: a documented argument form must be one the skill mentions somewhere.
    for (const s of doc.syntax ?? []) {
      const arg = /<([^>]+)>/.exec(s)?.[0];
      if (arg && n !== "BWESEO" && !text.includes(arg.replace(/^<|>$/g, "").split(" ")[0]))
        problems.push(`${n}: documented argument ${arg} is not described by the skill`);
    }
  }
  return problems;
}

// ---------------------------------------------------------------- generated sections
const skillCatalog = (root, ref) =>
  skillNames(root)
    .filter((n) => ref.skills[n]) // an undocumented skill is reported by checkConsistency, never silently dropped from the check
    .sort((a, b) => Object.keys(ref.skills).indexOf(a) - Object.keys(ref.skills).indexOf(b))
    .map((n) => {
      const d = ref.skills[n];
      const fm = frontmatter(readFileSync(join(root, "skills", n, "SKILL.md"), "utf8"));
      return [
        `### ${n}`,
        "",
        `**SKILL NAME:** \`/${n}\``,
        "",
        `**PURPOSE:** ${d.purpose}`,
        "",
        `**WHEN TO USE:** ${d.whenToUse}`,
        "",
        `**SYNTAX:**`,
        "",
        ...d.syntax.map((s) => `- \`${s}\``),
        "",
        `**ARGUMENTS:** ${d.arguments}`,
        "",
        `**EXAMPLES:**`,
        "",
        ...d.examples.map((e) => `- \`${e}\``),
        "",
        `**INPUTS:** ${d.inputs}`,
        "",
        `**OUTPUTS:** ${d.outputs}`,
        "",
        `**AUTOMATIC ACTIONS:** ${d.automatic}`,
        "",
        `**HUMAN APPROVAL REQUIREMENTS:** ${d.approval}`,
        "",
        `**EXTERNAL ACTIONS:** ${d.external}`,
        "",
        `**SAFETY RULES:** ${d.safety}`,
        "",
        `**NEXT TYPICAL STEP:** ${d.next}`,
        "",
        fm ? "" : "",
      ]
        .join("\n")
        .trimEnd();
    })
    .join("\n\n");

const quickReference = (root, ref) => {
  const rows = skillNames(root)
    .filter((n) => ref.skills[n])
    .sort((a, b) => Object.keys(ref.skills).indexOf(a) - Object.keys(ref.skills).indexOf(b))
    .map((n) => {
      const d = ref.skills[n];
      const forms = d.syntax.filter((s) => s !== `/${n}`).map((s) => s.slice(n.length + 1).trim());
      return `| \`/${n}\` | ${esc(firstSentence(d.purpose))} | \`${d.examples[0]}\` | ${forms.length ? esc(forms.map((f) => `\`${f}\``).join(" · ")) : "none"} | ${esc(d.approvalRequired)} | ${esc(d.externalEffect)} |`;
    });
  return ["| Command | Purpose | Typical Usage | Arguments | Human Approval? | External Effect? |", "|---|---|---|---|---|---|", ...rows].join("\n");
};

const directoryReference = (root) => {
  const lines = ["| Path | What it is |", "|---|---|"];
  for (const n of walkTop(root)) {
    const isDir = statSync(join(root, n)).isDirectory();
    lines.push(`| \`${n}${isDir ? "/" : ""}\` | ${esc(DIRECTORY_DESCRIPTIONS[n] ?? "**UNDOCUMENTED — add to DIRECTORY_DESCRIPTIONS**")} |`);
  }
  return lines.join("\n");
};

export function buildManual(root = defaultRoot) {
  const ref = loadReference(root);
  const template = readFileSync(join(root, "docs", "manual-template.md"), "utf8").replace(/\r\n/g, "\n");
  const version = readFileSync(join(root, "VERSION"), "utf8").trim();
  const schema = readConst(root, "src/validate-seo-data.mjs", "SCHEMA_VERSION") ?? "1";
  // TOC from the template's own level-2 headings.
  const headings = [...template.matchAll(/^## (.+)$/gm)].map((m) => m[1].trim());
  const toc = ["## Table of Contents", "", ...headings.map((h) => `- [${h.replace(/\s*\*\(generated\)\*/, "")}](#${slug(h)})`)].join("\n");
  const body = template
    .replace("{{ENGINE_VERSION}}", version)
    .replace("{{SCHEMA_VERSION}}", String(schema))
    .replace("{{LAST_UPDATED}}", ref.lastUpdated ?? "unknown")
    .replace("{{TOC}}", toc)
    .replace("{{SKILL_CATALOG}}", skillCatalog(root, ref))
    .replace("{{QUICK_REFERENCE}}", quickReference(root, ref))
    .replace("{{DIRECTORY_REFERENCE}}", directoryReference(root));
  return { text: body, headings, skills: skillNames(root) };
}

// Everything the manual and README must satisfy.
export function checkManual(root = defaultRoot) {
  const problems = [...checkConsistency(root)];
  const { text, skills } = buildManual(root);
  const file = join(root, MANUAL_NAME);
  if (!existsSync(file)) problems.push(`${MANUAL_NAME} does not exist — run node scripts/build-manual.mjs`);
  else if (readFileSync(file, "utf8").replace(/\r\n/g, "\n") !== text) problems.push(`${MANUAL_NAME} is stale — run node scripts/build-manual.mjs`);
  if (text.includes("UNDOCUMENTED")) problems.push("a top-level engine entry has no directory description (DIRECTORY_DESCRIPTIONS)");
  // The manual may only tell people to run skills that exist.
  const known = new Set(skills);
  for (const c of new Set(text.match(/\/BWESEO[A-Za-z]*/g) ?? [])) if (c !== "/BWESEO" && !known.has(c.slice(1))) problems.push(`the manual mentions ${c}, which is not a skill in this engine`);
  const readme = join(root, "README.md");
  if (!existsSync(readme)) problems.push("README.md does not exist");
  else if (!readFileSync(readme, "utf8").includes(MANUAL_NAME)) problems.push(`README.md does not link to ${MANUAL_NAME}`);
  return problems;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  if (check) {
    const problems = checkManual(defaultRoot);
    if (problems.length) {
      problems.forEach((p) => console.error(`✗ ${p}`));
      process.exit(1);
    }
    console.log(`✓ ${MANUAL_NAME} is current — every skill documented, no nonexistent skills, README links to it`);
  } else {
    const consistency = checkConsistency(defaultRoot);
    if (consistency.length) {
      consistency.forEach((p) => console.error(`✗ ${p}`));
      process.exit(1);
    }
    const { text, skills } = buildManual(defaultRoot);
    writeFileSync(join(defaultRoot, MANUAL_NAME), text);
    console.log(`✓ wrote ${MANUAL_NAME}: ${skills.length} skills, ${text.split("\n").length} lines`);
  }
}
