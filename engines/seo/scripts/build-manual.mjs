#!/usr/bin/env node
// Generates BWESEO-SKILLS-AND-PROCEDURES.md — the master operating manual — from the ACTUAL canonical engine, and
// checks that the manual, the skills and the README cannot silently disagree.
//
//   node scripts/build-manual.mjs           regenerate the manual
//   node scripts/build-manual.mjs --check   verify only; exit 1 on any problem (used by validate-canonical)
//
// Sources: docs/manual-template.md (hand-written procedures), docs/skills-reference.json (curated per-skill
// operating details), skills/<name>/SKILL.md (the skills themselves: names, descriptions, flags), VERSION and
// SCHEMA_VERSION (versions) and the real directory tree. Nothing here names a customer.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const MANUAL_NAME = "BWESEO-SKILLS-AND-PROCEDURES.md";
const defaultRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

