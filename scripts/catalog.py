#!/usr/bin/env python3
"""Generate (default) or --check SKILL-CATALOG.md from skills/*/SKILL.md."""
import json, re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
meta = json.loads((root/".claude-plugin/plugin.json").read_text())
extra = json.loads((root/"catalog-meta.json").read_text())
def fm(p):
    t = p.read_text(encoding="utf-8-sig")
    m = re.match(r"---\n(.*?)\n---", t, re.S)
    if not m: raise SystemExit(f"{p}: missing frontmatter")
    d = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        if _ and not line.startswith(" "): d[k.strip()] = v.strip()
    return d
rows = []
for p in sorted((root/"skills").glob("*/SKILL.md")):
    d = fm(p); n = d.get("name", p.parent.name); e = extra.get(p.parent.name, {})
    desc = d.get("description", "").replace("|", "\\|")
    short = (desc[:160] + "…") if len(desc) > 160 else desc
    rows.append(f"| {n} | {short} | {e.get('purpose','')} | `/{meta['name']}:{n}` | {meta['version']} | {e.get('dependencies','none')} | {e.get('projects','all')} | `skills/{p.parent.name}/SKILL.md` |")
out = ["# SKILL CATALOG", "", f"Generated by `scripts/catalog.py` from plugin `{meta['name']}` v{meta['version']}. Do not edit by hand.", "",
 "| Skill | Description | Purpose | Invocation | Version | Dependencies | Compatible projects | Source |", "|---|---|---|---|---|---|---|---|", *rows, ""]
text = "\n".join(out)
f = root/"SKILL-CATALOG.md"
if "--check" in sys.argv:
    sys.exit(0 if f.exists() and f.read_text()==text else "SKILL-CATALOG.md out of date: run python3 scripts/catalog.py")
f.write_text(text); print("wrote", f)
